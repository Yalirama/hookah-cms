    public static function norm(?string $s): string
    {
        $s = mb_strtolower(trim((string) $s));
        $s = str_replace('ё', 'е', $s);

        return trim(preg_replace('/[^\p{L}\p{N}\s]+/u', ' ', $s));
    }

    public static function match(?string $text, array $dict): array
    {
        $t = self::norm($text);
        if ($t === '') return [];
        $words = preg_split('/\s+/u', $t);
        $found = [];
        foreach ($dict as $label => $stems) {
            foreach ($stems as $stem) {
                $stem = self::norm($stem);
                if (str_contains($stem, ' ')) {
                    if (str_contains($t, $stem)) { $found[] = $label; break; }
                    continue;
                }
                $len = mb_strlen($stem);
                foreach ($words as $w) {
                    if (mb_strlen($w) < min($len, 3)) continue;
                    if (str_starts_with($w, $stem)) { $found[] = $label; continue 3; }
                    if ($len >= 5) {
                        $head = mb_substr($w, 0, $len);
                        if (mb_strlen($head) >= $len - 1 && levenshtein($head, $stem) <= 1) { $found[] = $label; continue 3; }
                    }
                }
            }
        }

        return array_values(array_unique($found));
    }

    public static function reasons(?string $text): array
    {
        if (self::norm($text) === '') return ['Причина не указана'];
        $m = self::match($text, self::REASONS);

        return $m ?: ['Другое'];
    }

    public static function season(int $month): string
    {
        return match (true) {
            in_array($month, [12, 1, 2]) => 'Зима',
            in_array($month, [3, 4, 5]) => 'Весна',
            in_array($month, [6, 7, 8]) => 'Лето',
            default => 'Осень',
        };
    }

    public static function daypart(int $hour): string
    {
        return match (true) {
            $hour >= 6 && $hour < 12 => 'Утро',
            $hour >= 12 && $hour < 18 => 'День',
            $hour >= 18 => 'Вечер',
            default => 'Ночь',
        };
    }
